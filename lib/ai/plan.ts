import 'server-only';

import { z } from 'zod';

import { generateJson, LlmError } from './llm';
import type { AnalysisResult } from '@/lib/analysis/analyze';
import type { Course } from '@/lib/data/types';

/**
 * 4-week learning path planner (RAG over the curated `courses` table).
 *
 * Retrieval: verified courses that teach the user's top gap skills.
 * Generation: the model sequences them into four weeks.
 *
 * Safety: the model may only return course IDs that were offered to it.
 * Every returned id is validated against the retrieved set; unknown ids are
 * dropped and missing weeks are filled deterministically. No URL is ever
 * generated by the model.
 */

export const LearningPathSchema = z.object({
  weeks: z
    .array(
      z.object({
        week: z.number().int().min(1).max(4),
        goal: z.string().min(5).max(200),
        courseIds: z.array(z.string()).max(2),
        practiceTask: z.string().min(5).max(400),
        estimatedHours: z.number().min(0).max(80),
      }),
    )
    .min(1)
    .max(4),
});

export type LearningPath = z.infer<typeof LearningPathSchema>;

export interface PlannedWeek {
  week: number;
  goal: string;
  courseIds: string[];
  practiceTask: string;
  estimatedHours: number;
  courses: Array<{
    id: string;
    title: string;
    provider: string | null;
    url: string | null;
    language: string | null;
    costUsd: number;
    durationHours: number | null;
    level: string | null;
    teachesSkills: string[];
  }>;
}

export interface LearningPathResult {
  weeks: PlannedWeek[];
  source: 'llm' | 'deterministic';
  provider: string | null;
  model: string | null;
  /** Course ids the model returned that do not exist in the catalogue. */
  rejectedCourseIds: string[];
  gapSkills: Array<{ id: string; name: string; nameBn: string | null }>;
}

const SYSTEM_PROMPT = `You build a realistic 4-week learning plan for a job seeker.

HARD RULES:
- Use ONLY course ids from the provided candidate list. Never invent an id, title or URL.
- One week has at most two courses.
- Order weeks from foundation to practice.
- The plan must fit roughly 6 to 10 hours per week.
- Write the goal and the practice task in the requested language.
- Do not change or invent any numbers about scores or demand.`;

interface Candidate {
  id: string;
  title: string;
  provider: string | null;
  language: string | null;
  durationHours: number | null;
  level: string | null;
  teaches: string[];
}

/** Verified courses that teach any of the top gap skills. */
export function selectCandidates(
  courses: Course[],
  gapSkillIds: string[],
  skillNames: Map<string, { name: string; nameBn: string | null }>,
  locale: string,
): Candidate[] {
  const wanted = new Set(gapSkillIds);

  const matched = courses
    .filter((course) => course.verified) // only verified rows ever reach a user
    .filter((course) => course.skillIds.some((id) => wanted.has(id)))
    .map<{ course: Course; overlap: number }>((course) => ({
      course,
      overlap: course.skillIds.filter((id) => wanted.has(id)).length,
    }))
    .sort((a, b) => {
      // Prefer the user's language, then free, then the most gap coverage.
      if (a.overlap !== b.overlap) return b.overlap - a.overlap;
      const langA = a.course.language === locale ? 0 : 1;
      const langB = b.course.language === locale ? 0 : 1;
      if (langA !== langB) return langA - langB;
      return a.course.costUsd - b.course.costUsd;
    })
    .slice(0, 12)
    .map(({ course }) => ({
      id: course.id,
      title: course.title,
      provider: course.provider,
      language: course.language,
      durationHours: course.durationHours,
      level: course.level,
      teaches: course.skillIds
        .filter((id) => wanted.has(id))
        .map((id) => skillNames.get(id)?.name ?? id),
    }));

  return matched;
}

/** Deterministic plan used when no model is available. */
export function deterministicPlan(candidates: Candidate[], gapNames: string[]): LearningPath {
  const weeks: LearningPath['weeks'] = [];
  const perWeek = Math.max(1, Math.ceil(Math.min(candidates.length, 8) / 4));

  for (let week = 1; week <= 4; week += 1) {
    const slice = candidates.slice((week - 1) * perWeek, week * perWeek);
    if (slice.length === 0 && week > 1) break;
    const focus = gapNames[(week - 1) % Math.max(gapNames.length, 1)] ?? 'core skills';
    weeks.push({
      week,
      goal: `Build momentum on ${focus}`,
      courseIds: slice.slice(0, 2).map((c) => c.id),
      practiceTask: `Apply what you learn to a small task using ${focus}.`,
      estimatedHours: slice.reduce((sum, c) => sum + Math.min(c.durationHours ?? 6, 10), 0) || 6,
    });
  }

  return { weeks };
}

function buildWeeks(
  path: LearningPath,
  candidatesById: Map<string, Candidate>,
  coursesById: Map<string, Course>,
): { weeks: PlannedWeek[]; rejected: string[] } {
  const rejected: string[] = [];
  const weeks: PlannedWeek[] = [];

  for (const week of path.weeks) {
    const courses: PlannedWeek['courses'] = [];
    for (const id of week.courseIds) {
      const candidate = candidatesById.get(id);
      const course = coursesById.get(id);
      if (!candidate || !course || !course.verified) {
        rejected.push(id);
        continue;
      }
      courses.push({
        id: course.id,
        title: course.title,
        provider: course.provider,
        url: course.url === 'TODO_VERIFY' ? null : course.url,
        language: course.language,
        costUsd: course.costUsd,
        durationHours: course.durationHours,
        level: course.level,
        teachesSkills: candidate.teaches,
      });
    }
    weeks.push({ ...week, courses });
  }

  return { weeks, rejected };
}

const LANGUAGE_NAME: Record<string, string> = { en: 'English', bn: 'Bangla (বাংলা)' };

export async function planLearningPath(params: {
  result: AnalysisResult;
  courses: Course[];
  locale: string;
  skillNames: Map<string, { name: string; nameBn: string | null }>;
}): Promise<LearningPathResult> {
  const { result, courses, locale, skillNames } = params;

  const gapSkillIds = (result.gaps?.gaps ?? []).slice(0, 5).map((g) => g.skillId);
  const gapSkills = gapSkillIds.map((id) => ({
    id,
    name: skillNames.get(id)?.name ?? id,
    nameBn: skillNames.get(id)?.nameBn ?? null,
  }));

  const candidates = selectCandidates(courses, gapSkillIds, skillNames, locale);
  const coursesById = new Map(courses.map((c) => [c.id, c]));
  const candidatesById = new Map(candidates.map((c) => [c.id, c]));

  if (candidates.length === 0) {
    return {
      weeks: [],
      source: 'deterministic',
      provider: null,
      model: null,
      rejectedCourseIds: [],
      gapSkills,
    };
  }

  let path = deterministicPlan(
    candidates,
    gapSkills.map((g) => g.name),
  );
  let source: 'llm' | 'deterministic' = 'deterministic';
  let provider: string | null = null;
  let model: string | null = null;

  try {
    const generated = await generateJson({
      system: SYSTEM_PROMPT,
      prompt: `Language: ${LANGUAGE_NAME[locale] ?? 'English'}

Gap skills to close, highest priority first:
${gapSkills.map((g, i) => `${i + 1}. ${g.name}`).join('\n')}

Candidate courses (you may ONLY use these ids):
${candidates.map((c) => `- id: ${c.id} | ${c.title} | ${c.provider ?? 'unknown provider'} | ${c.level ?? 'any'} | ~${c.durationHours ?? '?'}h | teaches: ${c.teaches.join(', ')}`).join('\n')}

Return JSON: {"weeks": [{"week": 1, "goal": string, "courseIds": [id], "practiceTask": string, "estimatedHours": number}]}`,
      schema: LearningPathSchema,
    });

    path = generated.data;
    source = 'llm';
    provider = generated.provider;
    model = generated.model;
  } catch (error) {
    if (!(error instanceof LlmError)) console.warn('[plan] unexpected error:', error);
  }

  const { weeks, rejected } = buildWeeks(path, candidatesById, coursesById);

  return {
    weeks: weeks.filter((w) => w.week >= 1 && w.week <= 4),
    source,
    provider,
    model,
    rejectedCourseIds: rejected,
    gapSkills,
  };
}
